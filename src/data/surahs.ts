export function getSurahById(id: number): Surah | undefined {
  return SURAHS.find((s) => s.id === id);
}

/** Vérifie que رقم الآية يقع ضمن حدود السورة */
export function isValidVerse(surahId: number, verse: number): boolean {
  const surah = getSurahById(surahId);
  if (!surah) return false;
  return Number.isInteger(verse) && verse >= 1 && verse <= surah.versesCount;
}

